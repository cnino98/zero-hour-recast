pub(super) fn registered(name: &str) -> Option<(u32, bool)> {
    MODULES
        .binary_search_by(|entry| entry.0.cmp(name))
        .ok()
        .map(|index| {
            let (_, mask, ai) = MODULES[index];
            (mask, ai)
        })
}

