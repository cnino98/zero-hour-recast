//! Authored `Behavior` `ModuleData`, separate from intrinsic `ThingTemplate` fields.
use super::{
    auto_find_healing, car_bombs, cleanup, contamination, countermeasures, death_callbacks,
    death_weapons, drones, fire, hazards, horde, income, instant_death, lifetimes, map_crates,
    overlord, point_defense, production_exit, reinforcement, sabotage, spy_vision, stealth,
    stealth_fighter,
};
use generals_assets::content::{ContentFile, Declaration};
use generals_sim::skirmish::{BehaviorData, Kind};
use std::error::Error;

pub(super) fn load(
    files: &[ContentFile],
    object: &Declaration,
    kind: Kind,
) -> Result<BehaviorData, Box<dyn Error>> {
    Ok(BehaviorData {
        create_object_die: super::create_object_die::load(files, object)?,
        eject_pilots: super::eject_pilot::load(files, object)?,
        bridges: super::bridge_behavior::load(files, object)?,
        neutron_blast: super::neutron_blast::load(object)?,
        bone_fx: super::bone_fx::load(files, object)?,
        command_button_hunts: super::command_button_hunt::rules(object)?,
        collision_weapons: super::fire::collide::load(files, object)?,
        toppling: super::toppling::load(files, object)?,
        mine_generators: super::minefield::generators(files, object)?,
        minefields: super::minefield::mines(files, object)?,
        hijackers: super::hijacker::updates(object)?,
        sticky_bombs: super::sticky_bomb::load(files, object)?,
        special_abilities: super::special_ability::load(files, object)?,
        assisted_targeting: super::assisted_targeting::load(object)?,
        mobs: super::spawn::mob_rules(files, object)?,
        spawns: super::spawn::load(object)?,
        spawn_exits: Vec::new(),
        slaves: super::drones::rules(files, object)?,
        prone: super::drones::prone_rules(object)?,
        supply_crippling: super::supply_crippling::load(object)?,
        granted_sciences: super::creation::granted_sciences(files, object)?,
        lock_weapons: super::creation::lock_weapons(object)?,
        object_creation: super::object_creation::load(files, object)?,
        auto_find_healing: auto_find_healing::load(&object.lines)?,
        lifetimes: lifetimes::lifetime_rules(&object.lines)?,
        deletions: lifetimes::deletion_rules(&object.lines)?,
        height_die: lifetimes::height_rules(&object.lines)?,
        ocl_update: reinforcement::timer(object)?,
        money_crate: map_crates::load(&object.lines)?,
        veterancy_crates: super::veterancy_crate::load(files, object)?,
        pilot_find_vehicle: super::pilot_find_vehicle::load(&object.lines)?,
        stealth: stealth::load(object)?,
        detectors: stealth::detectors(object)?,
        flammable: fire::flammable(object)?,
        fire_spread: fire::fire_spread(files, object)?,
        spy_vision: spy_vision::load(files, object)?,
        death_weapons: death_weapons::load(files, object)?,
        instant_death: instant_death::load(files, object)?,
        death_fx: death_callbacks::fx(files, object)?,
        crush_die: death_callbacks::crush(object)?,
        upgrade_die: death_callbacks::upgrade(files, object)?,
        destroy_die: death_callbacks::destroy(object)?,
        car_bomb_converter: car_bombs::converter(object)?,
        sabotage: sabotage::load(object)?,
        drone_upgrades: drones::upgrades(files, object)?,
        point_defense: point_defense::load(files, object)?,
        countermeasures: countermeasures::rules(&object.lines)?,
        bunker_busters: stealth_fighter::load(files, object)?,
        cleanup: cleanup::load(object)?,
        cleanup_area: cleanup::powers(object)?,
        fire_weapons: fire::weapon_update::load(files, object)?,
        damage_weapons: fire::when_damaged::load(files, object)?,
        firestorms: fire::firestorm::load(object)?,
        contamination: contamination::load(files, object)?,
        poisoned: hazards::poisoned(object)?,
        attachments: overlord::upgrades(files, object)?,
        replacement_names: super::fake_buildings::replacement_names(object)?,
        sub_object_upgrades: super::upgrades::sub_objects(object)?,
        propaganda: overlord::propaganda(object)?,
        horde: horde::load(files, object)?,
        hacking: income::load(object)?,
        radar_updates: crate::visibility_data::radar_updates(&object.lines)?,
        radar_upgrades: crate::visibility_data::radar_upgrades(&object.lines)?,
        radar_grants: crate::visibility_data::radar_grants(files, &object.lines)?,
        production_exit: production_exit(object, kind)?,
    })
}
